#!/usr/bin/env python3
"""Regenerate the automatic part of work/STATE.md from the tickets (no LLM needed).

  python scripts/agent/state.py [--milestone M1]

Only the block between the auto:start / auto:end markers is rewritten. The architect's own sections
below it ("Next action", "Decisions since last PR") are kept as they are.
"""
from __future__ import annotations

import argparse
import re

import common as c
import conflicts

START = "<!-- auto:start — generated by scripts/agent/state.py; edits inside are overwritten -->"
END = "<!-- auto:end -->"
MANUAL_DEFAULT = """
## Next action (architect)
1.

## Decisions since last PR
- none
"""


def last_note(t: c.Ticket) -> str:
    logs = [ln for ln in t.raw.split("\n") if ln.startswith("- ") and "status" in ln]
    if not logs:
        return ""
    m = re.search(r"\(by [^)]*\)(?::\s*(.*))?$", logs[-1])
    return (m.group(1) or "").strip() if m else ""


def render(root, cfg, milestone: str | None) -> str:
    tickets = [t for t in c.load_tickets(root, cfg).values()
               if not milestone or str(t.meta.get("milestone")) == milestone]
    try:
        branch = c.current_branch(root)
    except Exception:  # noqa: BLE001
        branch = "?"
    counts: dict[str, int] = {}
    for t in tickets:
        counts[t.status] = counts.get(t.status, 0) + 1
    lines = [START, f"# STATE  (generated {c.now()})",
             f"Milestone: {milestone or 'all'}   Branch: {branch}   "
             + " · ".join(f"{k} {v}" for k, v in sorted(counts.items())), "",
             "## Tickets", "| Ticket | Status | Tier | Round | Title |", "|---|---|---|---|---|"]
    order = {s: i for i, s in enumerate(["blocked", "escalated", "in_progress", "in_review", "changes_requested",
                                          "ready", "approved", "draft", "integrated", "done"])}
    for t in sorted(tickets, key=lambda x: (order.get(x.status, 99), x.id)):
        lines.append(f"| {t.id} | {t.status} | {t.meta.get('difficulty')} | {t.meta.get('review_round') or 0} "
                     f"| {t.meta.get('title')} |")
    batches, waiting, busy = conflicts.plan(root, cfg, milestone)
    lines += ["", "## Ready now (parallel-safe)",
              ("- " + ", ".join(t.id for t in batches[0])) if batches else "- none"]
    if waiting:
        lines.append("- waiting on deps: " + "; ".join(f"{k} ← {', '.join(v)}" for k, v in waiting.items()))
    need = [t for t in tickets if t.status in ("blocked", "escalated")]
    lines += ["", "## Needs architect"]
    lines += [f"- {t.id} {t.status}: {last_note(t) or '(see ticket log)'}" for t in need] or ["- none"]
    lines.append(END)
    return "\n".join(lines)


def write(root, cfg, milestone: str | None = None) -> None:
    path = root / cfg["paths"]["state"]
    old = path.read_text(encoding="utf-8") if path.exists() else ""
    if START.split(" —")[0] in old and END in old:
        head = old[: old.index(START.split(" —")[0])]
        tail = old[old.index(END) + len(END):]
    else:
        head, tail = "", MANUAL_DEFAULT
    path.write_text(head + render(root, cfg, milestone) + tail, encoding="utf-8")


def main():
    c.ensure_utf8_stdout()
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--milestone")
    a = ap.parse_args()
    root = c.control_root()
    cfg = c.load_config(root)
    write(root, cfg, a.milestone)
    print(f"wrote {cfg['paths']['state']}")


if __name__ == "__main__":
    main()
