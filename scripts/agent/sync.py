#!/usr/bin/env python3
"""Apply .agents/config.json to the tool-specific files. Run after every config edit.

  python scripts/agent/sync.py          # apply
  python scripts/agent/sync.py --check  # show what is configured, change nothing

Does:
  1. .claude/settings.json      -> "model" = architect.model; permissions.allow gets the command_prefixes variants
                                  of the workers' Bash commands (e.g. `Bash(rtk uv:*)`), so a prefixed command is
                                  allowed exactly when the plain one is (hooks and your own allow entries are kept)
  2. .claude/agents/executor-<tier>.md for every claude-cli / claude-subagent tier (model from the tier;
     run_loop.py does not need them, they are for running a ticket by hand from the architect session)
  3. .claude/skills/            <- copy of .agents/skills/ (no symlinks, works on Windows)
  4. prints the reviewer command and whether its executable is on PATH
"""
from __future__ import annotations

import argparse
import json
import re
import shutil

import common as c
from run_executor import allowed_tools

MARK = "<!-- generated by scripts/agent/sync.py from .agents/config.json — edit the config, not this file -->"

EXECUTOR_TEMPLATE = """---
name: executor-{tier_l}
description: Implements exactly one ticket whose difficulty is {tier} (prepared by scripts/agent/run_executor.py). Invoke with "Implement T-xxxx".
model: {model}
tools: Read, Grep, Glob, Bash, Write, Edit
---
{mark}
You implement exactly ONE ticket, given as "Implement T-xxxx". Below, <id> is that ticket id.
1. If `.worktrees/<id>/` or `work/.pack/<id>.md` is missing, run `python scripts/agent/run_executor.py <id>`.
2. Read `work/.pack/<id>.md`. It holds your rules, the ticket, the contracts and any review findings to address.
   Read nothing else unless the pack points you to it. Never read docs/human or work/archive.
3. Work ONLY inside `.worktrees/<id>/`. Edit only the files in `files_owned` (paths are relative to that folder).
   A hook blocks other edits. Need another file? Run
   `python scripts/agent/ticket.py status <id> blocked --by executor --note "<reason>"` and stop.
4. Tests first, unless the ticket says `tdd: false`: write ONLY the tests, then run
   `python scripts/agent/run_executor.py <id> --red` (commits them; they must fail). Then implement.
5. Fast check while working: `python scripts/agent/verify.py <id> --cwd .worktrees/<id> --ticket-only`.
   Run stack commands inside the worktree with the tool's own directory flag (e.g. `uv run --directory
   .worktrees/<id> ...`), one command per call; `cd` chains are not allowed. Never read lock/generated files.
6. Finish: `python scripts/agent/run_executor.py <id> --finish` (formats, commits, runs all gates, sets in_review).
   If it fails, fix and run it again, at most 3 times; then set the ticket blocked with the reason.
7. Reply in at most 5 lines: the --finish result and the files you changed. No code in the reply.
"""


def main():
    c.ensure_utf8_stdout()
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    root = c.control_root()
    cfg = c.load_config(root)
    claude = root / ".claude"
    tiers = cfg["executor"]["tiers"]

    print(f"architect model : {cfg.get('architect', {}).get('model')}")
    for name, tier in tiers.items():
        print(f"tier {name:<10} : {tier.get('runner')} / {tier.get('model')} / pack {tier.get('pack_tokens')} tok"
              f" / max {tier.get('max_files_owned')} files")
    wc = cfg["executor"].get("claude_cli", {}).get("command", [])
    if any(t.get("runner") == "claude-cli" for t in tiers.values()) and wc:
        print(f"worker cli      : {wc[0]}  [{'found' if shutil.which(wc[0]) else 'NOT on PATH'}]")
    rv = cfg.get("reviewer", {}).get("command", [])
    exe = rv[0] if rv else None
    print(f"reviewer        : {' '.join(rv)}  [{'found' if exe and shutil.which(exe) else 'NOT on PATH'}]")
    if a.check:
        return

    # 1. settings.json model
    sp = claude / "settings.json"
    settings = json.loads(sp.read_text(encoding="utf-8")) if sp.exists() else {}
    model = cfg.get("architect", {}).get("model")
    if model:
        settings["model"] = model
    else:
        settings.pop("model", None)
    cc = cfg["executor"].get("claude_cli", {})
    pres = [p.strip() for p in cc.get("command_prefixes", []) if p and p.strip()]
    tools = [x for x in (allowed_tools(cc) or "").split(",")
             if any(re.fullmatch(rf"\w+\({re.escape(p)} .+\)", x) for p in pres)]
    if tools:
        perms = settings.setdefault("permissions", {})
        allow = perms.setdefault("allow", [])
        allow += [x for x in tools if x not in allow]
    sp.parent.mkdir(parents=True, exist_ok=True)
    sp.write_text(json.dumps(settings, indent=2) + "\n", encoding="utf-8")
    print(f"wrote {sp.relative_to(root).as_posix()} (model={model})")

    # 2. executor subagents
    agents = claude / "agents"
    agents.mkdir(parents=True, exist_ok=True)
    for old in agents.glob("executor-*.md"):
        if MARK in old.read_text(encoding="utf-8"):
            old.unlink()
    for name, tier in tiers.items():
        if tier.get("runner") not in ("claude-subagent", "claude-cli"):
            continue
        out = agents / f"executor-{name.lower()}.md"
        out.write_text(EXECUTOR_TEMPLATE.format(tier=name, tier_l=name.lower(), model=tier.get("model", "sonnet"),
                                                mark=MARK), encoding="utf-8")
        print(f"wrote {out.relative_to(root).as_posix()} (model={tier.get('model')})")

    # 3. skills
    src, dst = root / ".agents" / "skills", claude / "skills"
    dst.mkdir(parents=True, exist_ok=True)
    for skill in sorted(p for p in src.iterdir() if p.is_dir()):
        target = dst / skill.name
        if target.exists():
            shutil.rmtree(target)
        shutil.copytree(skill, target)
    print(f"synced skills -> {dst.relative_to(root).as_posix()}")


if __name__ == "__main__":
    main()
